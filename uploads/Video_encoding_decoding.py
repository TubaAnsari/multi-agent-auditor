def decode_message_from_video(video_path):
    print(f"Starting decoding process from: {video_path}")

    # Open video
    cap = cv2.VideoCapture(video_path)
    if not cap.isOpened():
        print(f"Error: Cannot open video {video_path}")
        return None

    # Get video info
    fps = cap.get(cv2.CAP_PROP_FPS)
    width = int(cap.get(cv2.CAP_PROP_FRAME_WIDTH))
    height = int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT))
    total_frames = int(cap.get(cv2.CAP_PROP_FRAME_COUNT))

    print(f"Video Properties:")
    print(f"  Resolution: {width}x{height}")
    print(f"  FPS: {fps:.2f}")
    print(f"  Total frames: {total_frames}")

    # Extract LSBs from blue channel
    binary_bits = []
    frame_count = 0
    max_frames_to_process = min(450, total_frames)  # Process first 15 seconds at 30fps

    print(f"\nProcessing first {max_frames_to_process} frames...")

    while frame_count < max_frames_to_process:
        ret, frame = cap.read()
        if not ret:
            break

        # Extract LSB from each pixel's blue channel
        rows, cols = frame.shape[0], frame.shape[1]

        # Sample pixels (process every 10th pixel for speed)
        for row in range(0, rows, 10):
            for col in range(0, cols, 10):
                if len(binary_bits) < 10000:  # Limit bits to extract
                    blue_val = frame[row, col, 0]
                    lsb = blue_val & 1  # Get least significant bit
                    binary_bits.append(str(lsb))

        frame_count += 1

        # Show progress
        if frame_count % 30 == 0:
            print(f"  Processed {frame_count}/{max_frames_to_process} frames")

    cap.release()

    # Convert bits to string
    binary_string = ''.join(binary_bits)
    print(f"\nExtracted {len(binary_string)} bits")

    # Try to find the message
    message = ""
    found_end_marker = False

    # Look for the message in different alignments (handles bit shifts)
    for start_offset in range(8):
        current_binary = binary_string[start_offset:]
        temp_message = ""

        # Convert binary to characters
        for i in range(0, len(current_binary) - 7, 8):
            byte = current_binary[i:i+8]
            if len(byte) == 8:
                try:
                    char = chr(int(byte, 2))
                    temp_message += char

                    # Check for end marker
                    if temp_message.endswith("###"):
                        message = temp_message[:-3]  # Remove end marker
                        found_end_marker = True
                        print(f"Found message with offset {start_offset}")
                        break
                except:
                    continue

        if found_end_marker:
            break

    # If no end marker found, try to extract any readable data
    if not found_end_marker and len(binary_string) >= 40:
        print("End marker not found. Attempting to extract possible message...")

        # Try different segment of the binary data
        test_segments = [
            binary_string[:200],  # First 200 bits
            binary_string[100:300],  # Middle segment
            binary_string[-200:]  # Last 200 bits
        ]

        for idx, segment in enumerate(test_segments):
            test_message = ""
            # Try to decode as ASCII
            for i in range(0, len(segment) - 7, 8):
                byte = segment[i:i+8]
                if len(byte) == 8:
                    try:
                        char_val = int(byte, 2)
                        if 32 <= char_val <= 126:  # Printable ASCII
                            test_message += chr(char_val)
                    except:
                        continue

            if test_message and any(c.isdigit() for c in test_message):
                # Look for our message "12345" or parts of it
                if "12345" in test_message:
                    message = "12345"
                    found_end_marker = True
                    print(f"Found '12345' in segment {idx}")
                    break
                elif len(test_message) >= 5 and test_message[:5].isdigit():
                    message = test_message[:5]
                    print(f"Found digits '{message}' in segment {idx}")
                    break

    return message

