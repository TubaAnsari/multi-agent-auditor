def encode_robust_lsb(input_path, output_path, message):
    """
    Encode in multiple LSB bits for robustness
    """
    print(f"Encoding: '{message}'")

    message += "###"
    binary_msg = ''.join(format(ord(c), '08b') for c in message)

    cap = cv2.VideoCapture(input_path)
    fps = int(cap.get(cv2.CAP_PROP_FPS))
    width = int(cap.get(cv2.CAP_PROP_FRAME_WIDTH))
    height = int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT))

    fourcc = cv2.VideoWriter_fourcc(*'mp4v')
    out = cv2.VideoWriter(output_path, fourcc, fps, (width, height))

    # STRONG ENCODING: Use 3 LSB bits instead of 1
    # This creates visible-enough difference to survive compression

    bit_index = 0
    frame_idx = 0

    while True:
        ret, frame = cap.read()
        if not ret:
            break

        frame_idx += 1
        modified = frame.copy()

        # Encode in BLUE channel (least noticeable to human eye)
        rows, cols = height, width

        # Use fixed pattern for encoding
        encode_positions = []
        for i in range(len(binary_msg)):
            if bit_index + i < len(binary_msg):
                # Spread positions evenly
                row = (i * 23) % rows
                col = (i * 17) % cols
                encode_positions.append((row, col, binary_msg[bit_index + i]))

        for row, col, bit in encode_positions:
            if row < rows and col < cols:
                blue_val = modified[row, col, 0]

                # ENCODE IN 3 LSBs for robustness
                if bit == '1':
                    # Set last 3 bits to 111 (7)
                    new_val = (blue_val & 0xF8) | 0x07
                else:
                    # Set last 3 bits to 000 (0)
                    new_val = blue_val & 0xF8

                modified[row, col, 0] = new_val

        # Also encode in every 10th frame with HIGH contrast
        if frame_idx % 10 == 0:
            # Add sync marker (visible but not obvious)
            cv2.rectangle(modified, (5, 5), (15, 15), (255, 0, 0), -1)

        out.write(modified)

        bit_index += len(encode_positions)
        if bit_index >= len(binary_msg):
            # Message done, fill rest with original
            while True:
                ret, frame = cap.read()
                if not ret:
                    break
                out.write(frame)
            break

    cap.release()
    out.release()

    print(f"Encoded {len(binary_msg)} bits in {frame_idx} frames")
    print(f"Used 3 LSB bits per pixel for robustness")
    return True

