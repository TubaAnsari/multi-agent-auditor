def correct_bit_errors(received, expected):
    """Simple error correction using Hamming distance"""
    if len(received) != len(expected):
        return None

    # Calculate bit error positions
    errors = [i for i in range(len(received)) if received[i] != expected[i]]

    # If too many errors, can't correct
    if len(errors) > len(expected) // 3:
        return None

    # Try to correct (simple majority voting for now)
    corrected = list(received)

    # For each error position, try flipping
    for pos in errors:
        # Check neighbors
        neighbors = []
        for offset in [-2, -1, 1, 2]:
            neighbor_pos = pos + offset
            if 0 <= neighbor_pos < len(received):
                neighbors.append(received[neighbor_pos])

        # If most neighbors match expected, flip
        if neighbors and neighbors.count(expected[pos]) > len(neighbors) // 2:
            corrected[pos] = expected[pos]

    return ''.join(corrected)

def detect_flicker_pattern(brightness_signal):
    """Detect screen flicker patterns"""
    if len(brightness_signal) < 10:
        return None

    # Calculate differences
    diffs = np.diff(brightness_signal)

    # Find significant changes
    threshold = np.std(diffs) * 1.5
    significant_changes = np.where(np.abs(diffs) > threshold)[0]

    if len(significant_changes) < 5:
        return None

    # Create pattern from change directions
    pattern = ""
    for idx in significant_changes:
        if diffs[idx] > 0:
            pattern += 'U'  # Up
        else:
            pattern += 'D'  # Down

    return pattern

