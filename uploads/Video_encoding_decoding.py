def robust_decode(video_path, expected_message="12345"):
    print(f"Attempting robust decoding for: {video_path}")

    cap = cv2.VideoCapture(video_path)
    if not cap.isOpened():
        return None

    # Read first frame as reference
    ret, prev_frame = cap.read()
    if not ret:
        return None

    frame_data = []
    frame_count = 0

    # Process frames
    while True:
        ret, frame = cap.read()
        if not ret or frame_count > 300:  # First 10 seconds at 30fps
            break

        # Calculate frame signature (simplified)
        frame_diff = cv2.absdiff(frame, prev_frame)
        diff_score = np.mean(frame_diff)

        # Store frame data
        frame_data.append({
            'frame_num': frame_count,
            'diff_score': diff_score,
            'mean_blue': np.mean(frame[:,:,0])  # Blue channel average
        })

        prev_frame = frame.copy()
        frame_count += 1

    cap.release()

    # Analyze frame data for patterns
    if len(frame_data) < 10:
        print("Not enough frames for analysis")
        return None

    # Extract blue channel LSB pattern
    blue_pattern = ""
    for data in frame_data[:50]:  # First 50 frames
        mean_blue = data['mean_blue']
        lsb = int(mean_blue) & 1
        blue_pattern += str(lsb)

    print(f"Blue channel LSB pattern (first 50): {blue_pattern[:50]}")

    # Try to find known patterns
    # Convert "12345###" to binary for pattern matching
    target_message = expected_message + "###"
    target_binary = ''.join(format(ord(c), '08b') for c in target_message)

    # Look for target pattern in blue_pattern
    best_match = ""
    best_score = 0

    for i in range(len(blue_pattern) - len(target_binary) + 1):
        segment = blue_pattern[i:i+len(target_binary)]
        match_score = sum(1 for a, b in zip(segment, target_binary) if a == b)

        if match_score > best_score:
            best_score = match_score
            best_match = segment

    # Calculate match percentage
    match_pct = (best_score / len(target_binary)) * 100
    print(f"Best pattern match: {match_pct:.1f}%")

    if match_pct > 70:  # Good enough match
        print(f"High confidence match found!")
        return expected_message
    else:
        print(f"Low confidence match ({match_pct:.1f}%)")
        return None

