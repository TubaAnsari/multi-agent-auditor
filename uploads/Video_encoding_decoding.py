def advanced_decode_robust(video_path, expected_message="12345", frame_limit=300):

    print("=" * 70)
    print("ADVANCED DECODING WITH SIGNAL PROCESSING")
    print("=" * 70)

    # Step 1: Extract time-series signal from video
    print("\n1. Extracting signal from video...")

    cap = cv2.VideoCapture(video_path)
    if not cap.isOpened():
        print("ERROR: Cannot open video file")
        return None

    # Get video properties
    fps = int(cap.get(cv2.CAP_PROP_FPS))
    width = int(cap.get(cv2.CAP_PROP_FRAME_WIDTH))
    height = int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT))

    print(f"  Video: {width}x{height}, {fps} FPS")

    # Create multiple signal channels
    signals = {
        'brightness': [],
        'red_channel': [],
        'green_channel': [],
        'blue_channel': [],
        'high_freq': []
    }

    frame_count = 0
    prev_frame = None

    while frame_count < frame_limit:
        ret, frame = cap.read()
        if not ret:
            break

        # Convert to different color spaces
        gray = cv2.cvtColor(frame, cv2.COLOR_BGR2GRAY)
        hsv = cv2.cvtColor(frame, cv2.COLOR_BGR2HSV)

        # Extract features
        signals['brightness'].append(np.mean(gray))
        signals['red_channel'].append(np.mean(frame[:,:,2]))
        signals['green_channel'].append(np.mean(frame[:,:,1]))
        signals['blue_channel'].append(np.mean(frame[:,:,0]))

        # High frequency content (edges)
        if prev_frame is not None:
            diff = cv2.absdiff(gray, prev_frame)
            signals['high_freq'].append(np.mean(diff))

        prev_frame = gray.copy()
        frame_count += 1

        if frame_count % 100 == 0:
            print(f"  Processed {frame_count} frames...")

    cap.release()

    if frame_count == 0:
        print("ERROR: No frames could be read from video")
        return None

    print(f"  Extracted {frame_count} frames")

    # Step 2: Pre-process signals
    print("\n2. Pre-processing signals...")

    # Normalize all signals to 0-1 range
    processed_signals = {}
    for key, signal_data in signals.items():
        if len(signal_data) > 0:
            # Remove DC component
            signal_np = np.array(signal_data)
            signal_np = signal_np - np.mean(signal_np)

            # Normalize
            if np.max(np.abs(signal_np)) > 0:
                signal_np = signal_np / np.max(np.abs(signal_np))

            processed_signals[key] = signal_np

    # Combine signals (weighted average)
    weights = {'brightness': 0.4, 'red_channel': 0.2,
               'green_channel': 0.2, 'blue_channel': 0.2}

    combined_signal = np.zeros_like(list(processed_signals.values())[0])
    for key, weight in weights.items():
        if key in processed_signals:
            combined_signal += processed_signals[key] * weight

    print(f"  Signal length: {len(combined_signal)}")
    print(f"  Signal range: [{combined_signal.min():.3f}, {combined_signal.max():.3f}]")

    # Step 3: Apply digital signal processing
    print("\n3. Applying signal processing...")

    # Apply bandpass filter (0.1 Hz to 5 Hz - typical for our encoding)
    nyquist = fps / 2
    low = 0.1 / nyquist
    high = 5.0 / nyquist

    # Design butterworth filter
    b, a = signal.butter(4, [low, high], btype='band')
    filtered_signal = signal.filtfilt(b, a, combined_signal)

    # Smooth the signal
    window_size = max(3, fps // 10)  # 100ms window
    smoothed = np.convolve(filtered_signal, np.ones(window_size)/window_size, mode='same')

    # Step 4: Detect bit transitions
    print("\n4. Detecting bit transitions...")

    # Find peaks (bit transitions)
    peaks_positive, _ = signal.find_peaks(smoothed, height=0.1, distance=fps//2)
    peaks_negative, _ = signal.find_peaks(-smoothed, height=0.1, distance=fps//2)

    print(f"  Found {len(peaks_positive)} positive peaks")
    print(f"  Found {len(peaks_negative)} negative peaks")

    # Combine all transition points
